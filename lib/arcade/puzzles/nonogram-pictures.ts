import "server-only";

/**
 * The pictures Nonogram draws from.
 *
 * A nonogram is not a grid of numbers, it is a picture you cannot see yet, and
 * the moment it resolves into a thing is the whole reward. Every mainstream
 * picross ships hand-drawn art for exactly that reason. This file is that art
 * for the three rungs where a picture is legible -- 5x5, 10x10, 15x15 -- and
 * lib/arcade/puzzles/nonogram.ts falls back to its own symmetric generator
 * above that, where 400 and 625 squares are past what hand-drawn art can carry
 * and the shape itself has to do the work.
 *
 * **Every picture here is verified line-solvable by the test suite**, not by
 * eye. `nonogram-pictures.test.ts` runs `isNoGuessNonogram` over the whole
 * library and fails on any entry that needs a guess. That check is the reason
 * a picture may be shipped at all: lib/arcade/ante-up-nonogram.ts stakes real
 * Gold on a board being finishable by reasoning alone, and a lovely picture
 * that needs a coin flip is worse than no picture. When a new drawing fails
 * that test, thicken it -- a run of one square in a quiet line is almost
 * always what made it ambiguous, and two squares together usually fixes it.
 *
 * Authoring notes, learned the hard way here:
 *   - Solid shapes solve; scattered single squares do not.
 *   - A blank row or column is fine and often helps: an empty clue is settled
 *     instantly and gives every crossing line a free fact.
 *   - Symmetry reads as "a thing" to the eye even before it resolves.
 *
 * `server-only`, and reached only through lib/arcade/puzzles/nonogram-deal.ts,
 * for the same reason connections-puzzles.ts and word-stack-answers.ts are: a
 * browser holding this file could match the clues it was given against the
 * library and read the answer straight off. That is why the engine takes a
 * dealt picture rather than importing one.
 *
 * It is also why the library wants to keep growing. A player who memorised
 * every drawing at a rung would not have to solve the board, only recognise
 * it, and recognising is faster than reasoning. Mirroring doubles the clue
 * sets a drawing can produce (see nonogram-deal.ts) and the count per rung is
 * pinned by a test, but the honest defence is more art.
 */

export interface NonogramPicture {
  /** Shown only once the round is over. Never sent while it is live. */
  readonly name: string;
  readonly size: number;
  /** '#' / '.', row-major, `size * size` long. */
  readonly cells: string;
}

/** Joins authored rows into the flat encoding, checking the drawing is actually square. */
function picture(name: string, rows: readonly string[]): NonogramPicture {
  const size = rows.length;
  for (const row of rows) {
    if (row.length !== size) {
      throw new Error(`nonogram picture "${name}" is ${row.length} wide and ${size} tall`);
    }
  }
  return { name, size, cells: rows.join("") };
}

